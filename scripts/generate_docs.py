"""Regenerate docs/presets.md and the bundled registry YAML from code.

Run ``uv run python scripts/generate_docs.py`` after changing presets or
recognizers; ``tests/test_docs.py`` fails if the files are stale.
"""

from __future__ import annotations

from pathlib import Path

from canpii import PRESETS
from canpii.exporters import to_presidio_yaml

ROOT = Path(__file__).resolve().parents[1]


def presets_markdown() -> str:
    """Render docs/presets.md."""
    lines = [
        "# Policy presets",
        "",
        "> **Not legal advice.** Presets are starting points for engineering teams. Whether a",
        "> piece of data is personal information depends on context, purpose and the other",
        "> data it is combined with. Review any preset with your privacy officer or counsel.",
        "",
        "<!-- Generated by scripts/generate_docs.py - do not edit by hand. -->",
        "",
        "Use a preset to pick which entities to detect:",
        "",
        "```python",
        "from canpii import create_analyzer, get_preset",
        "",
        "analyzer = create_analyzer()",
        'preset = get_preset("phipa")',
        'analyzer.analyze(text, language="en", entities=preset.entity_list())',
        "```",
        "",
        "or to generate a gateway configuration:",
        "",
        "```bash",
        "canpii export --format litellm-config --preset phipa",
        "```",
        "",
    ]
    for p in PRESETS.values():
        lines += [
            f"## `{p.name}` — {p.title}",
            "",
            f"*Jurisdiction:* {p.jurisdiction} · *Law:* <{p.law_url}> · "
            f"*Languages:* {', '.join(p.languages)}",
            "",
            p.summary,
            "",
            "Entities: " + ", ".join(f"`{e}`" for e in p.entities),
            "",
        ]
        if p.notes:
            lines += ["Notes:", "", *[f"* {n}" for n in p.notes], ""]
    lines += [
        "## What presets do not do",
        "",
        "* They do not detect free-text health information (diagnoses, medications).",
        "  PHIPA and Law 25 cover far more than identifiers.",
        '* They do not make a dataset "de-identified" or "anonymized" in the legal sense.',
        "* They do not replace a privacy impact assessment.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Write generated files."""
    (ROOT / "docs" / "presets.md").write_text(presets_markdown(), encoding="utf-8")
    (ROOT / "src" / "canpii" / "conf" / "recognizers.yaml").write_text(
        to_presidio_yaml(), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
